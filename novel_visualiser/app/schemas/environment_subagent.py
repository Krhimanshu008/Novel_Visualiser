"""Novel Visualiser — Environment & Lighting Continuity Subagent Data Contracts.

Defines schemas for:
1. TimeOfDayEnum & WeatherConditionEnum (Canonical atmospheric states)
2. EnvironmentalDeepObservation (5-dimension CoT atmospheric reasoning)
3. LightingRigSpec (Physical key, fill, rim lighting vectors and Kelvin temperatures)
4. EnvironmentalAtmosphereCard (Canonical environmental asset stored in SQLite)
5. ShotEnvironmentAnchor (Runtime environmental tokens and lighting parameters)
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Optional
from pydantic import BaseModel, Field

from app.schemas.location_subagent import ArcHierarchyTag


class TimeOfDayEnum(str, Enum):
    """Canonical chronological time of day coordinates."""
    DAWN = "dawn"                          # 2500K-3000K low raking pink/gold
    MORNING = "morning"                    # 4500K fresh clean light
    NOON_HARSH = "noon_harsh"              # 5500K-6000K vertical overhead shadows
    AFTERNOON = "afternoon"                # 5000K neutral light
    GOLDEN_HOUR = "golden_hour"            # 3200K warm saturated amber/orange
    TWILIGHT_BLUE_HOUR = "twilight_blue_hour" # 8000K cold deep indigo/cyan diffuse
    NIGHT = "night"                        # 6500K moonlit or artificial streetlight
    MIDNIGHT_PITCH = "midnight_pitch"      # Near-total darkness, high chiaroscuro
    TIMELESS_VOID = "timeless_void"        # Dreamscapes, astral rifts, underworlds


class WeatherConditionEnum(str, Enum):
    """Canonical atmospheric and weather conditions."""
    CLEAR = "clear"
    OVERCAST_SMOG = "overcast_smog"
    ACID_DRIZZLE = "acid_drizzle"
    HEAVY_RAIN = "heavy_rain"
    DENSE_FOG = "dense_fog"
    ASH_FALL = "ash_fall"
    BLIZZARD = "blizzard"
    SUPERNATURAL_DARKNESS = "supernatural_darkness"


class EnvironmentalDeepObservation(BaseModel):
    """5-Dimension Observational Analysis generated by frontier thinking AI."""

    chronological_solar: str = Field(
        description="Solar/lunar altitude, azimuth, sky color gradient, and narrative time cues"
    )
    lighting_physics: str = Field(
        description="Key light source, direction, Kelvin rating, fill bounce, rim edge light, shadow falloff"
    )
    atmospheric_particles: str = Field(
        description="Smog density, suspended mist, dust motes, crepuscular god rays, airborne ash, wind speed"
    )
    foliage_ecosystem: str = Field(
        description="Vegetation species, decay state, dead weeds in fissures, withered branches, moss, wind deflection"
    )
    surface_weathering: str = Field(
        description="Ground saturation, puddles, specular asphalt reflections, frost riming, mud splatter"
    )


class LightingRigSpec(BaseModel):
    """Physical lighting rig specification for accurate ray and shadow compositing."""

    key_light_source: str = Field(
        description="Primary light source (e.g. 'Overhead flickering sodium-vapor streetlamp')"
    )
    key_light_direction: str = Field(
        description="Direction vector of key light (e.g. 'top-left 45-degree elevation')"
    )
    key_color_temperature_k: int = Field(
        default=2700,
        description="Estimated Kelvin temperature (2000K=candle, 2700K=sodium, 5500K=sun, 8000K=sky)"
    )
    fill_light_source: str = Field(
        default="Ambient sky bounce",
        description="Secondary ambient source illuminating shadow side"
    )
    rim_light_active: bool = Field(
        default=True,
        description="Whether rim/kicker backlighting outlines the character silhouette"
    )
    rim_light_color: str = Field(
        default="Pale cold cyan",
        description="Color or hue of rim edge illumination"
    )
    shadow_hardness: str = Field(
        default="soft_diffuse",
        description="Shadow sharpness: 'hard_cast', 'soft_diffuse', 'deep_chiaroscuro'"
    )


class EnvironmentalAtmosphereCard(BaseModel):
    """Canonical environmental asset card stored in SQLite for scene continuity."""

    environment_id: str = Field(description="Unique ID (e.g. 'env_outskirts_twilight_smog')")
    location_id: str = Field(description="Associated location ID (e.g. 'loc_outskirts_transit_bench_n24')")
    environment_name: str = Field(description="Descriptive title (e.g. 'Outskirts Twilight Acid Smog')")
    novel_arc: ArcHierarchyTag = Field(description="Hierarchical 3-tier story arc coordinate")
    valid_from_chapter: int = Field(default=1, description="First chapter where this environment takes effect")
    valid_to_chapter: Optional[int] = Field(default=None, description="Last chapter if superseded")
    time_of_day: TimeOfDayEnum = Field(default=TimeOfDayEnum.TWILIGHT_BLUE_HOUR)
    weather_condition: WeatherConditionEnum = Field(default=WeatherConditionEnum.OVERCAST_SMOG)
    
    observation: EnvironmentalDeepObservation = Field(
        description="5-dimension CoT reasoning analysis"
    )
    lighting_rig: LightingRigSpec = Field(
        description="Exact lighting vectors and color specifications"
    )

    # Prompt conditioning token blocks
    danbooru_lighting_tags: list[str] = Field(
        default_factory=list,
        description="Danbooru lighting tokens (e.g. 'volumetric lighting', 'rim light', 'sodium vapor light')"
    )
    danbooru_weather_tags: list[str] = Field(
        default_factory=list,
        description="Danbooru weather tokens (e.g. 'overcast', 'smog', 'crepuscular rays', 'fog')"
    )
    danbooru_foliage_tags: list[str] = Field(
        default_factory=list,
        description="Danbooru vegetation tokens (e.g. 'dead weeds in sidewalk cracks', 'withered branch')"
    )
    danbooru_surface_tags: list[str] = Field(
        default_factory=list,
        description="Danbooru surface moisture tokens (e.g. 'wet asphalt', 'puddle reflections')"
    )
    negative_environment_tags: list[str] = Field(
        default_factory=lambda: [
            "sunny blue sky", "bright daylight", "clear sky", "lush green grass",
            "blooming flowers", "clean dry ground", "lens glare"
        ],
        description="Negative prompt constraints locking out conflicting atmospheric traits"
    )

    # Palette & Color Tokens
    color_palette_hex: list[str] = Field(
        default_factory=lambda: ["#14161d", "#d47828", "#3b4f63", "#7a8a99"],
        description="Key color harmony hex swatches for the scene atmosphere"
    )
    reference_lut_path: Optional[str] = Field(
        default=None,
        description="Path to rendered 3D LUT or visual atmospheric grading chip"
    )


class ShotEnvironmentAnchor(BaseModel):
    """Runtime environmental anchor injected into diffusion / inpainting pipelines."""

    environment_card_id: str
    time_of_day: TimeOfDayEnum
    weather_condition: WeatherConditionEnum
    resolved_lighting_block: str = Field(
        description="Joined string of positive environmental & lighting Danbooru tags"
    )
    resolved_negative_block: str = Field(
        description="Joined string of negative environmental tags"
    )
    key_light_vector: str = Field(
        default="top_left",
        description="Directional vector for character shading and drop shadow generation"
    )
    shadow_direction: str = Field(
        default="bottom_right",
        description="Ground projection angle for cast shadows"
    )
    surface_moisture_level: float = Field(
        default=0.3,
        description="0.0 (bone dry) to 1.0 (submerged/heavy rain)"
    )

